"""動画のつなぎの図。各動画の頭に置く導入と、決める動画の終わりに置くまとめ。"""
from lesson_visuals import text, rect, path, arrow, circle, svg, INK, DIM, LINE, PAPER, ACCENT, check, cross

STEPS = ['作業の目的', '＋意味', '＋範囲', '＋条件']


def intro(prev_label, prev, right_label, hot, done, note, flow, move, title, focus=None):
    """全動画で、前の内容・今回の問い・手順の配置と接続を共通にする。"""
    a = rect(0, 0, 540, 184, PAPER, 12, LINE)
    a += text(24, 30, prev_label, 15, DIM, 700)
    for i, (tag, body) in enumerate(prev):
        y = 66 + i * 62
        a += text(24, y, tag, 15, DIM, 700)
        lines = [body[j:j+22] for j in range(0, len(body), 22)]
        a += text(136, y, lines, 17, INK, 700, gap=26)
        if i == 0: a += path('M24 104 H516', LINE, 1)
    a += rect(572, 0, 540, 184, PAPER, 12, LINE)
    a += text(596, 30, right_label, 15, DIM, 700)
    for i, tag in enumerate(['作業の目的', '意味', '範囲', '条件']):
        x = 596 + 123 * i
        is_hot = i in hot if isinstance(hot, tuple) else i == hot
        a += rect(x, 48, 110, 30, ACCENT if is_hot else PAPER, 8, ACCENT if is_hot else LINE)
        a += text(x + 55, 69, tag, 15, PAPER if is_hot else INK, 700, 'middle')
    if focus is None:
        focus = [('不足の確認', '欲しい表と比べる'), ('毎週の利用', '翌週にも使えるか？')]
    for i, (label, question) in enumerate(focus):
        x = 596 + 246 * i
        a += rect(x, 98, 222, 68, PAPER, 10, LINE)
        a += text(x + 16, 125, label, 18, INK, 700)
        a += text(x + 16, 153, question, 14, DIM)
    a += text(24, 208, note, 14, DIM)
    for i, (head, sub) in enumerate(flow):
        x = i * 284
        a += rect(x, 228, 260, 78, PAPER, 10, LINE)
        a += circle(x + 28, 267, 13, ACCENT, ACCENT)
        a += text(x + 28, 272, str(i + 1), 14, PAPER, 700, 'middle')
        a += text(x + 52, 259, head, 14, INK, 700)
        a += text(x + 52, 289, sub, 13, DIM)
        if i < 3: a += arrow(x + 260, 267, x + 284, 267)
    a += rect(0, 330, 1112, 50, PAPER, 10, ACCENT)
    a += text(24, 362, move, 16 if len(move) > 50 else 18, ACCENT, 700)
    return svg(title, a, 388)


def ending(learn, learn_sub, lines, done_head, done_sub, left_head, left_sub, nxt, nxt_sub, title, result='3回実行した結果'):
    """まとめの枚。主役は、上の「この動画で分かったこと」。下に、いまのプロンプト（1段1行）と3回実行した結果、いちばん下に次の動画を小さく置く。
    lines は (札, 1行の文, この動画で足したか) の並び。"""
    a = rect(0, 0, 1112, 112, PAPER, 14, ACCENT)
    a += text(24, 30, 'この動画で分かったこと', 13, DIM, 700)
    a += text(24, 68, learn, 24, INK, 700) + text(24, 96, learn_sub, 15, ACCENT, 700)
    # 左：いまのプロンプト。書類の形で、1段1行
    a += path('M0 132 H598 L620 154 V312 H0 Z M598 132 V154 H620', LINE, 2, PAPER) + rect(0, 132, 620, 180, 'none', 0, 'none')
    a += text(20, 156, 'いまのプロンプト', 12, DIM, 700)
    done = {t for t, _, _ in lines}
    rows = list(lines) + [(t, '次の動画で決める' if k == 0 else 'そのあとの動画で決める', None)
                          for k, t in enumerate([t for t in STEPS[1:] if t not in done])]
    for i, (tag, body, new) in enumerate(rows):
        y = 184 + i * 32
        if new is None:
            box = rect(20, y - 17, 112, 24, PAPER, 6, LINE)
            a += box.replace('stroke-width="2"', 'stroke-width="2" stroke-dasharray="4 4"') + text(76, y, tag, 12, DIM, 700, 'middle')
            a += text(146, y, body, 13, DIM)
        else:
            a += rect(20, y - 17, 112, 24, ACCENT if new else PAPER, 6, ACCENT if new else LINE)
            a += text(76, y, tag, 12, PAPER if new else DIM, 700, 'middle')
            a += text(146, y, body, 15, INK if new else DIM, 700 if new else 400)
    # 右：3回実行した結果
    a += rect(660, 132, 452, 180, PAPER, 12, LINE)
    a += text(684, 158, result, 13, DIM, 700)
    a += check(694, 192, ACCENT, .5) + text(716, 198, done_head, 17, INK, 700) + text(716, 220, done_sub, 13, DIM)
    a += path('M684 238 H1088', LINE, 1)
    a += cross(694, 264, DIM, .6) + text(716, 270, left_head, 17, INK, 700) + text(716, 292, left_sub, 13, DIM)
    # 下：次の動画
    a += rect(0, 332, 1112, 48, PAPER, 24, LINE)
    a += text(28, 362, '次の動画　' + nxt, 16, INK, 700) + text(300, 362, nxt_sub, 14, DIM)
    return svg(title, a, 384)


