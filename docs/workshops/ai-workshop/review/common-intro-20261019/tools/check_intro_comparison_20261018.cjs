const {chromium}=require('/home/daidaiiro/.npm/_npx/705bc6b22212b352/node_modules/playwright');
const fs=require('fs');
const path=require('path');
const dir=path.resolve(__dirname,'../workspace');
const slide=Number(process.argv[2]||3);
const expected=JSON.parse(fs.readFileSync(path.join(dir,`slide-${String(slide).padStart(2,'0')}.json`),'utf8'));
(async()=>{
 const browser=await chromium.launch({executablePath:'/home/daidaiiro/.cache/ms-playwright/chromium-1234/chrome-linux64/chrome',headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1480,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto(`http://127.0.0.1:8772/design-review.html?slide=${slide}#lead`);
 await page.waitForFunction(n=>document.querySelector('#deck').value==='lead'&&document.querySelector('#slide').value===String(n),slide);
 if(!await page.locator('#seven-slide-plan').count())throw Error('seven-slide plan missing');
 const verify=async()=>{
  const narration=await page.locator('#after-narration').textContent();
  if(!narration.includes(expected.heading)||!narration.includes(expected.narration.split('\n\n')[0]))throw Error('narration mismatch');
  const url=await page.locator('#after').getAttribute('src');
  if(!url.includes('common-intro-review/after.html?v='))throw Error('wrong deck');
 };
 await verify();
 await page.locator('#slide').selectOption(String(slide===1?2:slide-1));
 await page.locator('#slide').selectOption(String(slide));
 await verify();await page.waitForTimeout(650);
 const frame=page.frames().find(f=>f.url().includes('common-intro-review/after.html'));
 if(!frame)throw Error('after iframe missing');
 const heading=await frame.locator('.slide.on h2').textContent();
 if(heading!==expected.heading)throw Error('iframe heading mismatch');
 await page.locator('#before').scrollIntoViewIfNeeded();
 const prefix=`slide-${String(slide).padStart(2,'0')}-`;
 await page.screenshot({path:path.join(dir,prefix+'comparison-desktop.png')});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(dir,prefix+'comparison-mobile.png')});
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(overflow||errors.length)throw Error(JSON.stringify({overflow,errors}));
 fs.writeFileSync(path.join(dir,prefix+'browser-check.json'),JSON.stringify({slide,narration:true,iframeHeading:true,navigation:true,overflow,errors},null,2));
 console.log('comparison OK');await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
