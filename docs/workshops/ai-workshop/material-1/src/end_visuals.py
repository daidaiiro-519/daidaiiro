def e_next():
    """議事録の課題は、それぞれの業務の中に閉じている。PMがスケジュールを引くと、課題どうしのつながりが分からない。そこを扱うのが教材2。"""
    # 上：業務ごとに見ている課題。どの業務も、自分の業務の中だけを見ている
    owners = [('経費の精算業務', '日々の精算が回るか', ['承認の経路', '申請の締め日'], '課題の中身は、経理の記録の中'),
              ('システムの開発', '実装が進むか', ['既存データの移行'], '課題の中身は、開発の記録の中'),
              ('案件の進行管理（PM）', '案件の進行が止まらないか', ['旧システムの停止日'], '見えるのは、定例の議事録だけ')]
    for i, (biz, view, items, where) in enumerate(owners):
        x = i * 380
        a = (a if i else '') + rect(x, 0, 352, 112, PAPER, 12, LINE)
        a += text(x + 20, 28, biz, 15, INK, 700) + text(x + 20, 50, view + 'で見ている', 12, DIM)
        a += text(x + 20, 78, ' ・ '.join(items), 14, INK, 700) + text(x + 20, 100, where, 12, ACCENT if i == 2 else DIM, 700 if i == 2 else 400)
    # 真ん中：PMが引くスケジュール。課題どうしのつながりが分からない
    a += rect(0, 132, W, 196, PAPER, 12, ACCENT)
    a += text(24, 160, 'PMが引くスケジュール', 14, DIM, 700)
    a += text(560, 160, '9月30日', 12, DIM, anchor='middle') + text(860, 160, '10月7日', 12, DIM, anchor='middle')
    a += path('M560 168 V316 M860 168 V316', LINE, 1)
    bars = [('承認の経路', 300, 560), ('申請の締め日', 300, 560), ('既存データの移行', 300, 860), ('旧システムの停止日', 760, 860)]
    for j, (name, x1, x2) in enumerate(bars):
        y = 180 + j * 34
        a += text(24, y + 17, name, 14, INK, 700)
        a += rect(x1, y, x2 - x1, 22, PAPER, 6, LINE)
    # 分からないつながり。破線と「？」
    for (y1, y2, x, note) in [(202, 214, 600, '締め日は、承認の経路が決まってから？'),
                              (270, 282, 900, '移行が遅れたら、停止日は？')]:
        a += path(f'M{x} {y1} V{y2 + 10}', ACCENT, 2).replace('stroke-linecap', 'stroke-dasharray="3 4" stroke-linecap')
        a += circle(x, (y1 + y2) // 2 + 5, 11, PAPER, ACCENT) + text(x, (y1 + y2) // 2 + 10, '？', 13, ACCENT, 700, 'middle')
        a += text(x + 20, (y1 + y2) // 2 + 10, note, 12, ACCENT, 700)
    # 下：次の教材
    a += rect(0, 348, W, 64, PAPER, 12, LINE)
    a += icon(24, 368, 'book', INK, .5)
    a += text(72, 387, '教材2　言葉の定義', 19, INK, 700)
    a += text(260, 387, '業務ごとに「課題」が何を指すかを確かめ、各業務の課題の中身まで見られるようにする', 15, INK)
    return svg('議事録の課題は、それぞれの業務の中に閉じている。PMがスケジュールを引くと、課題どうしのつながりが分からない。そこを扱うのが教材2', a, 418)
