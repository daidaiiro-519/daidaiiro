"""動画のつなぎの図。各動画の頭に置く導入と、追記する動画の終わりに置くまとめ。"""
from lesson_visuals import text, rect, path, arrow, circle, svg, INK, DIM, LINE, PAPER, ACCENT, check, cross

STEPS = ['もとのプロンプト', '＋意味', '＋範囲', '＋条件']


def intro(prev_label, prev, right_label, hot, done, note, flow, move, title):
    """左上に前の動画で分かったこと、右上に追記する順番の中での位置、下にこの動画の進め方と動き。
    hot はこの動画で扱う段（無ければ None）、done は追記済みの段の数（もとのプロンプトを含む）。"""
    # 左上：前の動画で分かったこと。カードの中は線で区切るだけにし、枠を重ねない
    a = rect(0, 0, 540, 176, PAPER, 12, LINE)
    a += text(24, 32, prev_label, 14, DIM, 700)
    for i, (k, v) in enumerate(prev):
        y = 84 + i * 58
        a += path(f'M24 {y - 30} H516', LINE, 1)
        a += text(24, y, k, 14, DIM, 700) + text(152, y, v, 16, INK, 700)
    # 右上：追記する順番を、階段の線で示す。この動画の段だけ強調する
    a += rect(572, 0, 540, 176, PAPER, 12, LINE)
    a += text(596, 32, right_label, 14, DIM, 700)
    X0, Y0, SW, SH = 600, 74, 120, 24
    d = f'M{X0} {Y0}'
    for i in range(4):
        d += f' H{X0 + (i + 1) * SW}' + (f' V{Y0 + (i + 1) * SH}' if i < 3 else '')
    a += path(d, LINE, 2)
    for i, t in enumerate(STEPS):
        x, y = X0 + i * SW, Y0 + i * SH
        is_hot = i == hot
        if is_hot:
            a += path(f'M{x} {y} H{x + SW}', ACCENT, 5)
        a += text(x + SW / 2, y - 10, t, 16 if is_hot else 15, ACCENT if is_hot else (INK if i < done else DIM), 700, 'middle')
        if is_hot:
            a += text(x + SW / 2, y + 22, 'この動画', 13, ACCENT, 700, 'middle')
    a += text(596, 164, note, 13, DIM)
    for i, (t, sub) in enumerate(flow):
        x = i * 284
        a += rect(x, 228, 260, 76, PAPER, 10, LINE)
        a += circle(x + 28, 266, 13, ACCENT, ACCENT) + text(x + 28, 271, str(i + 1), 14, PAPER, 700, 'middle')
        a += text(x + 52, 260, t, 15 if len(t) <= 12 else 14, INK, 700) + text(x + 52, 284, sub, 13, DIM)
    a += rect(0, 324, 1112, 50, PAPER, 10, ACCENT)
    a += text(24, 355, move, 16, ACCENT, 700)
    return svg(title, a, 378)


def ending(learn, learn_sub, lines, done_head, done_sub, left_head, left_sub, nxt, nxt_sub, title):
    """まとめの枚。主役は、上の「この動画で分かったこと」。下に、いまのプロンプト（1段1行）と3回実行した結果、いちばん下に次の動画を小さく置く。
    lines は (札, 1行の文, この動画で足したか) の並び。"""
    a = rect(0, 0, 1112, 112, PAPER, 14, ACCENT)
    a += text(24, 30, 'この動画で分かったこと', 13, DIM, 700)
    a += text(24, 68, learn, 24, INK, 700) + text(24, 96, learn_sub, 15, ACCENT, 700)
    # 左：いまのプロンプト。書類の形で、1段1行
    a += path('M0 132 H598 L620 154 V312 H0 Z M598 132 V154 H620', LINE, 2, PAPER) + rect(0, 132, 620, 180, 'none', 0, 'none')
    a += text(20, 156, 'いまのプロンプト', 12, DIM, 700)
    done = {t for t, _, _ in lines}
    rows = list(lines) + [(t, '次の動画で追記する' if k == 0 else 'そのあとの動画で追記する', None)
                          for k, t in enumerate([t for t in STEPS[1:] if t not in done])]
    for i, (tag, body, new) in enumerate(rows):
        y = 184 + i * 32
        if new is None:
            box = rect(20, y - 17, 112, 24, PAPER, 6, LINE)
            a += box.replace('stroke-width="2"', 'stroke-width="2" stroke-dasharray="4 4"') + text(76, y, tag, 12, DIM, 700, 'middle')
            a += text(146, y, body, 13, DIM)
        else:
            a += rect(20, y - 17, 112, 24, ACCENT if new else PAPER, 6, ACCENT if new else LINE)
            a += text(76, y, tag, 12, PAPER if new else DIM, 700, 'middle')
            a += text(146, y, body, 15, INK if new else DIM, 700 if new else 400)
    # 右：3回実行した結果
    a += rect(660, 132, 452, 180, PAPER, 12, LINE)
    a += text(684, 158, '3回実行した結果', 13, DIM, 700)
    a += check(694, 192, ACCENT, .5) + text(716, 198, done_head, 17, INK, 700) + text(716, 220, done_sub, 13, DIM)
    a += path('M684 238 H1088', LINE, 1)
    a += cross(694, 264, DIM, .6) + text(716, 270, left_head, 17, INK, 700) + text(716, 292, left_sub, 13, DIM)
    # 下：次の動画
    a += rect(0, 332, 1112, 48, PAPER, 24, LINE)
    a += text(28, 362, '次の動画　' + nxt, 16, INK, 700) + text(300, 362, nxt_sub, 14, DIM)
    return svg(title, a, 384)


