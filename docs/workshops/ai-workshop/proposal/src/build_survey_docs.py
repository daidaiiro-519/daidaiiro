"""設問の正本 survey.json から、アンケート・効果測定案と、Forms の Copilot に渡すプロンプトを組む。

  python3 build_survey_docs.py      # out/survey-and-evaluation.md と out/forms-copilot-prompts.md を書く
"""
import json, pathlib

HERE = pathlib.Path(__file__).parent
OUT = HERE.parent / 'out'
SV = json.loads((HERE / 'survey.json').read_text())
Q = SV['questions']
F = {f['id']: f for f in SV['forms']}
LIMIT = 2000  # Forms の Copilot に1回で渡すプロンプトの文字数の上限（利用者の指定）


def numbered(f):
    """フォームの設問に、フォームの中の通し番号を振る。"""
    n, out = 0, []
    for s in f['sections']:
        for k in s['keys']:
            n += 1
            out.append((n, s, k))
    return out


def num_of(f):
    return {k: n for n, _, k in numbered(f)}


def sec_first(f):
    """セクションの先頭の設問の番号。分岐の移動先を番号で書くため。"""
    first = {}
    for n, s, _ in numbered(f):
        first.setdefault(s['id'], (n, s['name']))
    return first


def where(f, to):
    if to == 'end':
        return 'フォームの終わり'
    n, name = sec_first(f)[to]
    return f'{n}（{name}）'


def branch_rows(f):
    nums = num_of(f)
    rows = []
    for b in f['branch']:
        if 'section' in b:
            s = next(x for x in f['sections'] if x['id'] == b['section'])
            rows.append((f'{nums[s["keys"][-1]]}のあと（セクション「{s["name"]}」の終わり）', '―', where(f, b['to'])))
        else:
            rows.append((f"{nums[b['q']]}", b['answer'], where(f, b['to'])))
    return rows


def count(f):
    ks = [k for s in f['sections'] for k in s['keys']]
    return len(ks), sum('任意' in Q[k]['answer'] for k in ks)


def form_table(f):
    rows = ['| 番号 | セクション | 設問 | 回答の形 | 使う指標・用途 |', '|---|---|---|---|---|']
    for n, s, k in numbered(f):
        q = Q[k]
        rows.append(f"| {n} | {s['name']} | {q['text']} | {q['answer']} | {q['use']} |")
    return '\n'.join(rows)


def branch_table(f):
    rows = branch_rows(f)
    if not rows:
        return '分岐は無い。\n'
    out = ['| 設問 | 回答 | 移動先 |', '|---|---|---|'] + [f'| {a} | {b} | {c} |' for a, b, c in rows]
    return '\n'.join(out) + '\n'


# ── Forms の Copilot に渡すプロンプト ─────────────────────────────

LEAD = {
    'pre': '社内AI活用ワークショップの「事前アンケート」を作成してください。',
    'app': '社内のAI活用ワークショップの「参加時アンケート」を作成してください。準備期間の希望者が、教材をすべて見たあとに、目的を書いて参加を申し込みます。',
    'end': '社内のAI活用ワークショップの「参加者の終了時アンケート」を作成してください。参加者がワークショップの終わりに回答します。',
    'hend': '社内のAI活用ワークショップの準備期間の希望者のうち、ワークショップに参加しなかった人が回答する短いアンケートを作成してください。',
}
RULE = 'クイズや点数は不要です。設問文と選択肢は、言い換えずにそのまま使ってください。【】はセクションの区切りです。（任意）と書いた設問以外は必須、（複数選択）・（最大）と書いた設問以外は1つ選択です。'


def kind(q):
    """回答の形を短く書く。必須は既定なので書かず、任意だけを書く。"""
    a = q['answer']
    opt = '・任意' if '任意' in a else ''
    if a.startswith('長いテキスト'):
        return '記述' + opt, None
    if a.startswith('行：'):
        rows, cols = a[2:].split('　列：')
        return 'リッカート', f'行：{rows}\n列：{cols}'
    multi = '複数選択' in q['text'] or '最大' in q['text']
    return '', a


def _to_next(f, b):
    """分岐の移動先が、その設問のセクションの次のセクションか。"""
    if 'q' not in b or b['to'] == 'end':
        return False
    ids = [x['id'] for x in f['sections']]
    here = next(x['id'] for x in f['sections'] if b['q'] in x['keys'])
    i = ids.index(here)
    return i + 1 < len(ids) and ids[i + 1] == b['to']


def prompt(fid):
    f = F[fid]
    out = [LEAD[fid] + RULE, '']
    n = 0
    for s in f['sections']:
        out.append(f"【{s['name']}】")
        for k in s['keys']:
            n += 1
            q = Q[k]
            t, extra = kind(q)
            out.append(f"{n}. {q['text']}" + (f"（{t}）" if t else ''))
            if extra:
                out.append(extra)
    # 次のセクションへ進む分岐は Forms の既定と同じなので、プロンプトには書かない（文字数を上限に収めるため）
    rows = [r for r, b in zip(branch_rows(f), f['branch']) if not _to_next(f, b)]
    if rows:
        out += ['', '分岐（ほかの回答は次のセクションへ）：' + '／'.join(f'{a}で「{b}」→{c.split("（")[0]}' if b != '―' else f'{a.split("（")[0]}→{c.split("（")[0]}' for a, b, c in rows)]
    text = '\n'.join(out).rstrip()
    assert len(text) <= LIMIT, f'{fid} のプロンプトが {len(text)} 字ある（上限 {LIMIT}）'
    return text


