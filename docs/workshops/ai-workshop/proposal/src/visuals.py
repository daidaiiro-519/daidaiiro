def agenda(cards, hot=None):
    """説明の順序を、左から右へのカードで示す。施策の2枚には何番目の施策かを、最後の1枚には「最後に」を添える。"""
    def em(s):  # 文字の幅（全角を1とする）
        return sum(.56 if ord(c) < 128 else 1 for c in s)
    n = len(cards); gap = 40 if n <= 3 else 30
    # カードの幅は、見出しと項目の長さに合わせて配分する（4枚のときに長い見出しが枠を出ないようにする）
    need = [max(em(c[1]) * 22, max(em(s_) * 17 + 22 for s_ in c[2])) + 48 for c in cards]
    room = 1112 - gap * (n - 1)
    ws = [room / n] * n if n <= 3 else [x + (room - sum(need)) / n for x in need]
    a = ''
    h = 44 + 40 * max(len(c[2]) for c in cards) + 40
    x = 0
    for i, ((tag, head, items), w) in enumerate(zip(cards, ws)):
        on = (i == hot)
        a += rect(x, 0, w, h, PAPER, 12, ACCENT if on else LINE)
        if tag:
            a += text(x + 24, 34, tag, 14, ACCENT if on else DIM, 700)
        a += text(x + 24, 72, head, 22, ACCENT if on else INK, 700)
        for j, s_ in enumerate(items):
            y = 116 + j * 38
            a += circle(x + 30, y - 6, 4, LINE, LINE) + text(x + 46, y, s_, 17, DIM)
        if i < n - 1:
            a += arrow(x + w + 5, h // 2, x + w + gap - 5, h // 2)
        x += w + gap
    return svg('説明の順序。' + '、'.join(c[1] for c in cards), a, h + 4)


