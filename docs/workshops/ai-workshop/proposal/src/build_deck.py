def _fq(n, q):
    q = {k: _plain(v) if isinstance(v, str) else v for k, v in q.items()}
    a = q['answer']
    if a.startswith('長いテキスト'):
        ans = f'<div class="ws-fa">記述欄（{"必須" if "必須" in a else "任意"}）</div>'
    elif a.startswith('行：'):
        rows_, cols_ = a[2:].split('　列：')
        ans = ('<div class="ws-fo"><span class="ws-fl">行</span>' + ''.join(f'<span class="ws-fc">{esc(r)}</span>' for r in rows_.split('／')) + '</div>'
               + '<div class="ws-fo"><span class="ws-fl">列</span>' + ''.join(f'<span class="ws-fc ws-r">{esc(c)}</span>' for c in cols_.split('／')) + '</div>')
    else:
        k = 'ws-k' if ('複数選択' in q['text'] or '最大' in q['text']) else 'ws-r'
        ans = '<div class="ws-fo">' + ''.join(f'<span class="ws-fc {k}">{esc(c)}</span>' for c in a.split('／')) + '</div>'
    return f'<div class="ws-fq"><span class="ws-fn">{n}</span><div class="ws-fb"><p class="ws-ft">{esc(q["text"])}</p>{ans}</div></div>'
