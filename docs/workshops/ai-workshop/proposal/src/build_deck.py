def _polite(s):
    for a, b in (('測定する。','測定します。'),('確認する。','確認します。'),('使用する。','使用します。'),
                 ('記録する。','記録します。'),('含めない。','含めません。'),('選択肢になる。','選択肢になります。'),
                 ('登録する。','登録します。'),('比較する。','比較します。'),('取得元。','取得元です。'),('答える。','答えます。'),('分岐させる。','分岐させます。'),('選ぶ。','選びます。'),('起点。','起点です。'),('使う。','使います。'),('分岐する。','分岐します。'),('もらう。','もらいます。'),('取る。','取ります。'),('聞く。','聞きます。')):
        s = s.replace(a, b)
    return s

