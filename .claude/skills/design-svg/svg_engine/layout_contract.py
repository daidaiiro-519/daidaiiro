"""配置戦略が守る契約 ── 4つの戦略が共有する型を、中立な場所に置く。

置き場所を分けているのは、共有される契約を実装の1つが所有してはいけないため。
以前は層状配置（sugiyama）が戻り値の型を持ち、環状・放射の木・格子・合成が
そこから借りていた（実測5箇所）。その形には2つ困りごとがある。

1. 層状配置を差し替える・撤去する・切り出すという判断が、借りている全モジュール
   を巻き込む。契約は変わっていないのに、実装の都合が契約の利用者へ届く。
2. 依存グラフの見え方が歪む。格子配置は層状配置の振る舞いを1行も使っていないのに、
   依存しているように見え、依存の深さの解釈を誤らせる。

契約は「呼び出し側が何を必要としているか」の視点で定義する。どの戦略も、
ここに書かれた形を返す約束をするだけで、互いを知らない。
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class LayoutResult:
    """配置戦略が返すもの。どの戦略もこの形を返す。

    座標のような戦略固有の入力は、この契約に入れない ── 入れると、その入力を
    使わない戦略まで受け取ることになる。呼び出し側が束ねて渡す。
    """
    positions: dict[str, tuple[float, float]]   # 実節点id → (x, y) 左上
    edge_paths: dict[int, list[tuple[float, float]]]  # 辺の通し番号 → 通る点の並び
    width: float
    height: float


class UnsupportedByStrategy(ValueError):
    """この配置のやり方では描けない、と配置側が申告する。

    入力が誤っているのではなく、この戦略の能力の外にあるという意味。
    別の描き方（網掛けや色で重なりを表す等）なら描けるので、
    コアの入力検査として拒むのではなく、戦略の側から申告する。
    """
